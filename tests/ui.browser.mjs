import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from '@playwright/test';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto(process.env.UI_BASE_URL || 'http://localhost:5173');
 await page.locator('.generate').waitFor();await page.evaluate(()=>document.fonts.ready);
 assert.equal(await page.locator('[name="dimensions"]').count(),7);
 assert.equal(await page.locator('#grade').inputValue(),'2');
 assert.equal(await page.locator('[data-topic="cnm_p047"]').getAttribute('aria-pressed'),'true');
 await page.locator('#topic-search').fill('口诀');
 assert.ok(await page.locator('.topic-chip').count()>1);
 await page.locator('#topic-search').fill('不存在的知识');
 await page.locator('.generate').click();await page.locator('#notice').filter({hasText:'没有可选知识点'}).waitFor();
 await page.locator('#topic-search').fill('');
 await page.locator('[data-topic="cnm_p047"]').click();
 await page.locator('.generate').click();await page.locator('.question-card').first().waitFor();
 assert.equal(await page.locator('.question-card').count(),6);
 const first=page.locator('.question-card').first();
 const initialPrompts=await page.locator('.question-card .student-prompt').allTextContents();
 const expected=await page.evaluate(async()=>{const e=await import('/src/engine.js'),p=await import('/src/planner.js');const q=(await p.planWorksheet(await e.loadCatalog(),{grade:2,semester:'all',topicId:'cnm_p047',dimensions:['fill'],level:1,count:6,seed:'little-house-01',mode:'custom'},e)).questions[0];return {answer:q.answer,parts:q.answerSpec?.parts||[]};});
 if(await first.locator('.answer-input').count())await first.locator('.answer-input').first().fill('wrong');
 else await first.locator(`input[type=radio]:not([value="${expected}"])`).first().check();
 await first.locator('[data-action=check]').click();
 await first.locator('.feedback').filter({hasText:/答对|还差|部分/}).waitFor();
 await first.locator('[data-action=hint]').click();assert.equal(await first.locator('.hint').count(),1);
 await first.locator('[data-action=hint]').click();assert.match(await first.locator('.hint').innerText(),/2\/2/);
 await page.locator('#teacher').check();assert.equal(await page.locator('.teacher-answer').count(),6);
 await page.locator('#print-answers').check();await page.waitForFunction(()=>document.querySelectorAll('#print-root .answer-page').length>0);assert.equal(await page.locator('#print-root .answer-page').count(),1);
 await page.locator('#columns').selectOption('1');await page.waitForFunction(()=>document.querySelectorAll('#print-root .student-page .columns-1').length>0);assert.ok(await page.locator('#print-root .student-page .columns-1').count()>0);
 const download=page.waitForEvent('download');await page.locator('[data-action=export]').click();assert.match((await download).suggestedFilename(),/\.json$/);
 await page.emulateMedia({media:'print'});assert.equal(await page.locator('#app').isVisible(),false);assert.equal(await page.locator('#print-root').isVisible(),true);
 await page.emulateMedia({media:'screen'});
 await page.locator('.nav-item[data-view=map]').click();await page.locator('.map-node').first().click();assert.equal(await page.locator('.map-inspector h3').count(),1);
 await page.locator('.nav-item[data-view=history]').click();assert.match(await page.locator('.real-stats').innerText(),/1/);
 await page.locator('[data-action=retry]').click();assert.equal(await page.locator('.question-card').count(),1);
 for(const part of expected.parts){const input=page.locator(`input[name="answer-0-${part.id}"]`);if(await input.count())await input.fill(String(part.spec.value));}
 if(!expected.parts.length&&await page.locator('#answer-0').count())await page.locator('#answer-0').fill(expected.answer);
 if(await page.locator('input[name="answer-0-answer"][type=radio]').count())await page.locator(`input[name="answer-0-answer"][value="${expected.answer}"]`).check();
 await page.locator('[data-action=check]').click();assert.equal(await page.locator('.feedback.correct').count(),1);
 await page.locator('.nav-item[data-view=history]').click();assert.equal(await page.locator('[data-action=retry]').count(),0);
 page.once('dialog',dialog=>dialog.dismiss());await page.locator('[data-action=clear]').click();assert.match(await page.locator('.real-stats').innerText(),/2/);
 page.once('dialog',dialog=>dialog.accept());await page.locator('[data-action=clear]').click();assert.equal((await page.locator('.real-stats strong').allTextContents()).join(','),'0,0,0');
 await page.locator('.nav-item[data-view=configure]').click();
 await page.locator('#grade').selectOption('2');
 await page.locator('.generate').click();await page.locator('.question-card').first().waitFor();
 assert.deepEqual(await page.locator('.question-card .student-prompt').allTextContents(),initialPrompts);
 const priorSeed=await page.locator('.worksheet-toolbar .muted').innerText();await page.locator('[data-action=variant]').click();
 assert.notEqual(await page.locator('.worksheet-toolbar .muted').innerText(),priorSeed);
 await page.locator('.nav-item[data-view=configure]').click();await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await mkdir('artifacts',{recursive:true});
 await page.screenshot({path:'artifacts/mobile-ui.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('UI browser smoke passed: filtering, empty state, real generation, answer checking, two-stage hints, teacher answers, independent print answers, single-column print, JSON download, print isolation, map exploration, real history, mobile overflow.');
} finally {await browser.close();}
